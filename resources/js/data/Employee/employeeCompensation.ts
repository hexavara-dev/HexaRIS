import { employee } from './employee';
import { employmentContract } from './employmentContract';

const empId = (employeeNumber: string) => employee.find((e) => e.employee_number === employeeNumber)!.id;
const contractId = (employeeNumber: string) => employmentContract.find((c) => c.employee_id === empId(employeeNumber))!.id;

// No currencies table exists yet in this codebase — every compensation below is a single,
// fixed IDR placeholder id, since PT Abadi Jaya only pays out in Rupiah for now.
const CURRENCY_ID_IDR = 'f1a2b3c4-0001-4f1a-8b2c-678901234ef0';

export type SalaryType = 'monthly' | 'hourly' | 'project';

export type CompensationChangeReason = 'contract_signed' | 'annual_increase' | 'promotion' | 'minimum_wage_adjustment' | 'correction';

export type OutOfBandType = 'below_min' | 'above_max';

export interface EmployeeCompensation {
    id: string;
    is_effective_now: boolean;
    effective_from: string;
    effective_to: string;
    base_salary: number;
    salary_type: SalaryType;
    change_reason: CompensationChangeReason | null;
    is_out_of_band: boolean | null;
    out_of_band_type: OutOfBandType | null;
    out_of_band_reason: string | null;
    currency_id: string;
    employee_id: string;
    contract_id: string;
}

